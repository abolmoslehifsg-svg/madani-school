/* ---------- اعتبارسنجی کد ملی ---------- */
function validNid(n) {
  n = en(n);
  if (!/^\d{10}$/.test(n) || /^(\d)\1{9}$/.test(n)) return false;
  let s = 0;
  for (let i=0; i<9; i++) s += (+n[i]) * (10 - i);
  const r = s % 11;
  return (r < 2 && +n[9] === r) || (r >= 2 && +n[9] === 11 - r);
}
